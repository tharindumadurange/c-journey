#include <stdio.h>

int main(){
    int a = 10;
    int b = 3;
    int sum, difference, product, quotient, remainder;

    printf("Sum of a and b is %d\n",sum = a+b);
    printf("Difference of a and b is %d\n",difference = a-b);
    printf("Product of a and b is %d\n",product = a*b);
    printf("Quotient of a divided by b is %d\n",quotient = a/b);
    printf("Remainder of a divided by b is %d\n",remainder = a%b);
    return 0;
}